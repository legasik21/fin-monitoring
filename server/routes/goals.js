import { Router } from 'express';
import { and, desc, eq, sql } from 'drizzle-orm';
import db from '../db.js';
import { goals } from '../schema.js';
import { parseAmount } from '../lib/money.js';
import {
  HttpError,
  ID_ERROR,
  MONEY_ERROR,
  bodyOf,
  parseId,
  pgError,
  route,
} from '../lib/ledger.js';
import { serializeGoal } from '../serialize.js';

const router = Router();

const NOT_FOUND = 'Ціль не знайдено';
const TITLE_ERROR = 'Вкажіть назву цілі';
const TARGET_ERROR = 'Сума цілі має бути більшою за 0';
const TITLE_MAX = 200;

// Largest value numeric(14,2) holds. A contribution that would push the goal
// past it is a 400, not a Postgres overflow 500.
const MAX_AMOUNT = '999999999999.99';

/** Trimmed title, ≤ 200 code points (Postgres char_length). Throws the 400s. */
function parseTitle(raw) {
  const title = typeof raw === 'string' ? raw.trim() : '';
  if (!title) throw new HttpError(400, TITLE_ERROR);
  if ([...title].length > TITLE_MAX) throw new HttpError(400, 'Назва занадто довга');
  return title;
}

function urlId(req) {
  const id = parseId(req.params.id);
  if (!id) throw new HttpError(400, ID_ERROR);
  return id;
}

const owned = (id, userId) => and(eq(goals.id, id), eq(goals.user_id, userId));

async function getGoal(id, userId) {
  const [row] = await db.select().from(goals).where(owned(id, userId)).limit(1);
  return row ?? null;
}

// GET /api/goals — newest first
router.get(
  '/',
  route(async (req, res) => {
    const rows = await db
      .select()
      .from(goals)
      .where(eq(goals.user_id, req.userId))
      .orderBy(desc(goals.created_at), desc(goals.id));
    res.json(rows.map(serializeGoal));
  })
);

// GET /api/goals/:id
router.get(
  '/:id',
  route(async (req, res) => {
    const row = await getGoal(urlId(req), req.userId);
    if (!row) throw new HttpError(404, NOT_FOUND);
    res.json(serializeGoal(row));
  })
);

// POST /api/goals  { title, target_amount }
router.post(
  '/',
  route(async (req, res) => {
    const body = bodyOf(req);
    const title = parseTitle(body.title);
    const target = parseAmount(body.target_amount);
    if (!target) throw new HttpError(400, TARGET_ERROR);

    // current_amount defaults to 0; `achieved` is generated by Postgres.
    const [created] = await db
      .insert(goals)
      .values({ user_id: req.userId, title, target_amount: target })
      .returning();
    res.status(201).json(serializeGoal(created));
  })
);

// PATCH /api/goals/:id  { title?, target_amount?, contribute?, current_amount? }
// `current_amount` sets the saved amount, `contribute` adds to it (after the
// set, when both are given). The addition runs in SQL on the exact numeric.
router.patch(
  '/:id',
  route(async (req, res) => {
    const userId = req.userId;
    const id = urlId(req);
    const body = bodyOf(req);

    const set = {};
    if (body.title !== undefined) set.title = parseTitle(body.title);
    if (body.target_amount !== undefined) {
      set.target_amount = parseAmount(body.target_amount);
      if (!set.target_amount) throw new HttpError(400, TARGET_ERROR);
    }
    let current = null;
    if (body.current_amount !== undefined) {
      current = parseAmount(body.current_amount, { allowZero: true });
      if (current === null) throw new HttpError(400, MONEY_ERROR);
    }
    let contribute = null;
    if (body.contribute !== undefined) {
      contribute = parseAmount(body.contribute);
      if (!contribute) throw new HttpError(400, MONEY_ERROR);
    }

    let newCurrent = null;
    if (current !== null && contribute !== null) {
      newCurrent = sql`${current}::numeric + ${contribute}::numeric`;
    } else if (contribute !== null) {
      newCurrent = sql`${goals.current_amount} + ${contribute}::numeric`;
    } else if (current !== null) {
      newCurrent = sql`${current}::numeric`;
    }
    if (newCurrent) set.current_amount = newCurrent;

    // Nothing to change: answer with the goal as it is (still ownership-checked).
    if (Object.keys(set).length === 0) {
      const row = await getGoal(id, userId);
      if (!row) throw new HttpError(404, NOT_FOUND);
      return res.json(serializeGoal(row));
    }

    // The overflow guard lives in the WHERE, so an over-large sum updates no row
    // instead of raising; 22003 stays mapped as a backstop.
    let updated;
    try {
      [updated] = await db
        .update(goals)
        .set(set)
        .where(
          newCurrent
            ? and(owned(id, userId), sql`${newCurrent} <= ${MAX_AMOUNT}::numeric`)
            : owned(id, userId)
        )
        .returning();
    } catch (err) {
      if (pgError(err)?.code === '22003') throw new HttpError(400, MONEY_ERROR);
      throw err;
    }
    if (updated) return res.json(serializeGoal(updated));

    // No row updated: either not the caller's goal, or the guard refused the sum.
    if (!(await getGoal(id, userId))) throw new HttpError(404, NOT_FOUND);
    throw new HttpError(400, MONEY_ERROR);
  })
);

// DELETE /api/goals/:id
router.delete(
  '/:id',
  route(async (req, res) => {
    const id = urlId(req);
    const [removed] = await db
      .delete(goals)
      .where(owned(id, req.userId))
      .returning({ id: goals.id });
    if (!removed) throw new HttpError(404, NOT_FOUND);
    res.json({ ok: true });
  })
);

export default router;
